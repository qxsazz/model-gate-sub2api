export const dayIndex = (day: string) =>
  Math.floor(new Date(day + 'T04:00:00Z').getTime() / 86400000)
export function lunarDate(day: string): string {
  try {
    const f = new Intl.DateTimeFormat('zh-CN-u-ca-chinese', {
      month: 'long',
      day: 'numeric',
      timeZone: 'Asia/Shanghai',
    })
    if (f.resolvedOptions().calendar !== 'chinese') return '农历日期暂不可用'
    const parts = f.formatToParts(new Date(day + 'T04:00:00Z')),
      month = parts.find((p) => p.type === 'month')?.value,
      n = Number(parts.find((p) => p.type === 'day')?.value)
    if (!month || !Number.isInteger(n) || n < 1 || n > 30)
      return '农历日期暂不可用'
    const digits = ['', '一', '二', '三', '四', '五', '六', '七', '八', '九']
    const text =
      n === 10
        ? '初十'
        : n === 20
          ? '二十'
          : n === 30
            ? '三十'
            : n < 10
              ? '初' + digits[n]
              : n < 20
                ? '十' + digits[n - 10]
                : '廿' + digits[n - 20]
    return '农历 ' + month + text
  } catch {
    return '农历日期暂不可用'
  }
}
