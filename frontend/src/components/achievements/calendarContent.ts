const dayNumber = (day: string) => Date.parse(day + 'T00:00:00Z') / 86_400_000

export function calendarChoice<T>(day: string, items: readonly T[], offset = 0): T {
  const number = dayNumber(day) + offset
  // Count calendar days continuously across months. Advance one extra slot per pass
  // so that a new cycle does not repeat the previous cycle in the same order of dates.
  const position = number + Math.floor(number / items.length)
  return items[((position % items.length) + items.length) % items.length]!
}

